export class DiskAllowance {
	gridValues: number[][];
	rowRanges: number[][];
	columnRanges: number[][];

	constructor(gridValues: number[][]) {
		this.gridValues = gridValues;
		// Define your rowRanges and columnRanges here (they remain fixed for all datasets)
		this.rowRanges = [
			[160, 200],
			[201, 250],
			[251, 300],
			[301, 350],
			[351, 400],
			[401, 450],
			[451, 500],
			[501, 550],
			[551, 600],
			[601, 650],
			[651, 700],
			[701, 800],
			[801, 900],
			[901, 1000],
			[1001, 1100],
			[1101, 1205],
			[1206, 1315],
			[1316, 1430],
			[1431, 1550],
			[1551, 1675],
			[1676, 1805],
			[1806, 1940],
			[1941, 2080],
			[2081, 2225],
			[2226, 2375],
		];

		this.columnRanges = [
			[0, 40],
			[41, 62],
			[63, 100],
			[101, 130],
			[131, 165],
			[166, 205],
			[206, 250],
			[251, 300],
			[301, 355],
			[356, 415],
			[416, 480],
			[481, 550],
			[551, 625],
			[626, 705],
			[706, 790],
			[791, 880],
			[881, 975],
			[976, 1075],
			[1076, 1180],
			[1181, 1290],
			[1291, 1404],
		];
	}

	findValue(
		rowValue: number,
		columnValue: number
	): number | undefined {
		// Find the matching row and column indexes based on the values provided
		const rowIndex = this.findRowIndex(rowValue);
		const columnIndex = this.findColumnIndex(columnValue);

		// If the rowIndex or columnIndex is undefined, return undefined
		if (rowIndex === undefined || columnIndex === undefined) {
			return undefined;
		}

		// Use the row and column indexes to retrieve the corresponding value from gridValues
		if (
			rowIndex >= 0 &&
			rowIndex < this.gridValues.length &&
			columnIndex >= 0 &&
			columnIndex < this.gridValues[rowIndex].length
		) {
			const gridValue = this.gridValues[rowIndex][columnIndex];
			return gridValue;
		}

		// Return undefined if the row or column is out of bounds
		return undefined;
	}

	private findRowIndex(rowValue: number): number | undefined {
		for (let i = 0; i < this.rowRanges.length; i++) {
			const [min, max] = this.rowRanges[i];
			if (rowValue >= min && rowValue <= max) {
				return i;
			}
		}

		return undefined; // Row value not found in any range
	}

	private findColumnIndex(columnValue: number): number | undefined {
		for (let i = 0; i < this.columnRanges.length; i++) {
			const [min, max] = this.columnRanges[i];
			if (columnValue >= min && columnValue <= max) {
				return i;
			}
		}

		return undefined; // Column value not found in any range
	}
}

